"""NotebookLM, joined to Zotero by a link the researcher carries across.

NotebookLM has no API a personal Google account can reach — see
``docs/NOTEBOOKLM.md`` for what was checked and when. So this module does not
try to drive it. It does the four things around it that a program can do well
and a person does badly:

1. **Prepares what goes in.** Zotero knows a URL or a DOI for many sources,
   and NotebookLM takes a list of URLs pasted in one go. It also takes pasted
   text, which is how the researcher's own selected passages — the one thing
   no crawler can fetch — get into the notebook. Files with neither are staged
   into a single folder so that "select all" replaces hunting through Zotero's
   hashed storage directories.
2. **Holds the link.** The researcher makes the notebook and pastes its URL
   back. One notebook per project, or one per source, or both.
3. **Writes that link into Zotero**, so the notebook is reachable from the
   item it is about — which is where the researcher will next be looking.
4. **Keeps what comes back.** A briefing doc, a study guide, a timeline, a
   mind map read out — whatever NotebookLM was asked for, pasted back and kept
   beside its evidence.

Nothing here is generated by this app, and nothing here can become a card.
"""

